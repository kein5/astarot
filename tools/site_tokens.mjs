// Writes the user guide's colour tokens (site/theme/tokens.css) and checks them.
//
//   node tools/site_tokens.mjs          write site/theme/tokens.css
//   node tools/site_tokens.mjs --check  exit 1 if the file is stale or a colour breaks a rule
//
// The dark values are DESIGN.md's colours, read from its front matter, so the guide wears the
// app's palette and follows it when the app's changes (docs/design/site-redesign, S-02). The
// light values are the guide's own, made by DESIGN.md's rule for deriving colours: a brand colour
// where one fits the role, else Dark Plum or Lilac with only the lightness changed (OKLCH hue
// within 3°, chroma no higher than the source's). The check holds that rule and the contrast each
// role needs, against the canvas, the rail and the surface of its scheme.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const OUT = join(root, 'site/theme/tokens.css')

const BRAND = { darkPlum: '#261633', lilac: '#a47af5', offWhite: '#fafafc', white: '#ffffff' }

// Role → DESIGN.md colour. `on-primary` is not in DESIGN.md: it is the text on a Lilac fill,
// which DESIGN.md's primary button writes in the canvas colour (Dark Plum).
const ROLES = [
  'canvas', 'rail', 'surface', 'border', 'field-border', 'text', 'secondary-text', 'description-text',
  'primary', 'on-primary', 'primary-hover', 'state-active', 'focus', 'state-warning', 'state-failed',
  'readout-rule',
]

// The light scheme (docs/design/site-redesign/README.md, 3.2) and what each value comes from.
const LIGHT = {
  canvas: ['#fafafc', 'Off-White'],
  rail: ['#f6f1fa', BRAND.darkPlum],
  surface: ['#ffffff', 'White'],
  border: ['#dfd7e8', BRAND.darkPlum],
  'field-border': ['#887995', BRAND.darkPlum],
  text: ['#261633', 'Dark Plum'],
  'secondary-text': ['#544760', BRAND.darkPlum],
  'description-text': ['#6a5d75', BRAND.darkPlum],
  primary: ['#a47af5', 'Lilac'],
  'on-primary': ['#261633', 'Dark Plum'],
  // #9c72ed in the proposal; one step less chroma keeps it within Lilac's.
  'primary-hover': ['#9c72ec', BRAND.lilac],
  'state-active': ['#7046b6', BRAND.lilac],
  focus: ['#7e55c7', BRAND.lilac],
  'state-warning': ['#865813', 'state-warning'],
  'state-failed': ['#944a47', 'state-failed'],
  'readout-rule': ['#a47af5', 'Lilac'],
}

// What each role must reach against the grounds it sits on: 4.5:1 for text, 3:1 for the edge of
// a control and a focus ring. The Lilac fill (a button) sits on the canvas and on surfaces, never
// on the rail; Lilac as text is `state-active`.
const ALL = ['canvas', 'rail', 'surface']
const CONTRAST = {
  text: [4.5, ALL], 'secondary-text': [4.5, ALL], 'description-text': [4.5, ALL], 'state-active': [4.5, ALL],
  'state-warning': [4.5, ALL], 'state-failed': [4.5, ALL], 'field-border': [3, ALL], focus: [3, ALL],
  primary: [3, ['canvas', 'surface']],
}
// The light warning and failure colours keep the hue of the dark ones at a low chroma (3.2).
const STATE_CHROMA = 0.1005

function designColors() {
  const design = readFileSync(join(root, 'DESIGN.md'), 'utf8')
  const front = design.slice(design.indexOf('colors:'), design.indexOf('typography:'))
  const colors = {}
  for (const [, name, value] of front.matchAll(/\n\s+([\w-]+):\s*"(#[0-9a-fA-F]{6})"/g)) colors[name] = value.toLowerCase()
  return colors
}

function schemes() {
  const design = designColors()
  const dark = {}
  for (const role of ROLES) {
    const value = role === 'on-primary' ? design.canvas : design[role]
    if (!value) throw new Error(`DESIGN.md has no colour ${role}`)
    dark[role] = value
  }
  const light = Object.fromEntries(ROLES.map((role) => [role, LIGHT[role][0]]))
  return { dark, light, design }
}

// Shadows and the backdrop behind a dialog: Dark Plum's own darkness, not neutral black.
const SHADES = {
  light: { shadow: 'rgba(38, 22, 51, 0.16)', backdrop: 'rgba(38, 22, 51, 0.6)' },
  dark: { shadow: 'rgba(12, 5, 18, 0.5)', backdrop: 'rgba(12, 5, 18, 0.82)' },
}

const block = (selector, scheme, values, indent = '') =>
  [
    `${indent}${selector} {`,
    `${indent}  color-scheme: ${scheme};`,
    ...ROLES.map((role) => `${indent}  --a-${role}: ${values[role]};`),
    `${indent}  --a-link: var(--a-state-active);`,
    ...Object.entries(SHADES[scheme]).map(([name, value]) => `${indent}  --a-${name}: ${value};`),
    `${indent}}`,
  ].join('\n')

function render() {
  const { dark, light } = schemes()
  return `/* Generated by tools/site_tokens.mjs. Do not edit: change DESIGN.md (the dark values) or the
   light table in that script, then run \`node tools/site_tokens.mjs\`.

   The guide's role tokens (docs/design/site-redesign, 3.1). Parts use only these; theme/custom.css
   gives Rspress's own variables their values. Light is the default; Rspress puts .rp-dark on <html>
   for the dark scheme, from the reader's choice or the OS. Without scripts no class is set, so the
   OS setting picks the scheme (the media query matches only before Rspress has run). */
${block(':root', 'light', light)}

${block('html.rp-dark', 'dark', dark)}

@media (prefers-color-scheme: dark) {
${block("html:not(.rp-dark):not([style*='color-scheme'])", 'dark', dark, '  ')}
}

/* The same in both schemes: DESIGN.md's radii, spacing and motion. */
:root {
  --a-radius-hairline: 2px;
  --a-radius-small: 4px;
  --a-radius-control: 8px;
  --a-radius-dialog: 12px;
  --a-space-xsmall: 4px;
  --a-space-small: 8px;
  --a-space-medium: 16px;
  --a-space-large: 24px;
  --a-space-section: 40px;
  --a-ease: cubic-bezier(0.2, 0, 0, 1);
  --a-ease-settle: cubic-bezier(0.3, 1.25, 0.4, 1);
  --a-motion-fast: 120ms;
  --a-motion: 220ms;
}

/* A reader who asks for less motion gets the end state at once. */
@media (prefers-reduced-motion: reduce) {
  :root {
    --a-motion-fast: 0ms;
    --a-motion: 0ms;
  }
}
`
}

// sRGB → relative luminance and OKLCH, as CSS Color 4 converts them (src-ui's brandPalette test).
const linear = (hex) =>
  hex
    .slice(1, 7)
    .match(/../g)
    .map((pair) => parseInt(pair, 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
const luminance = (hex) => {
  const [r, g, b] = linear(hex)
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const contrast = (a, b) => {
  const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m)
  return (x + 0.05) / (y + 0.05)
}
const oklch = (hex) => {
  const [r, g, b] = linear(hex)
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
  const a = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s
  const bb = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s
  return { lightness: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, chroma: Math.hypot(a, bb), hue: ((Math.atan2(bb, a) * 180) / Math.PI + 360) % 360 }
}
const hueApart = (x, y) => {
  const turn = Math.abs(x - y) % 360
  return Math.min(turn, 360 - turn)
}

function problems() {
  const { dark, light, design } = schemes()
  const found = []
  const brandNames = { 'Off-White': BRAND.offWhite, White: BRAND.white, 'Dark Plum': BRAND.darkPlum, Lilac: BRAND.lilac }
  for (const [role, [value, source]] of Object.entries(LIGHT)) {
    if (brandNames[source]) {
      if (value !== brandNames[source]) found.push(`light ${role} ${value} should be ${source} ${brandNames[source]}`)
      continue
    }
    // A state colour keeps the hue of the dark one, at the lightness of the light link.
    const from = source.startsWith('#') ? source : design[source]
    const [made, base] = [oklch(value), oklch(from)]
    const limit = source.startsWith('#') ? base.chroma : STATE_CHROMA
    if (hueApart(made.hue, base.hue) > 3) found.push(`light ${role} ${value}: hue ${made.hue.toFixed(1)}° is more than 3° from ${from} (${base.hue.toFixed(1)}°)`)
    if (made.chroma > limit) found.push(`light ${role} ${value}: chroma ${made.chroma.toFixed(4)} is above ${limit.toFixed(4)}`)
  }
  for (const [name, values] of [['light', light], ['dark', dark]]) {
    for (const [role, [need, grounds]] of Object.entries(CONTRAST)) {
      for (const ground of grounds) {
        const ratio = contrast(values[role], values[ground])
        if (ratio < need) found.push(`${name} ${role} ${values[role]} on ${ground} ${values[ground]}: ${ratio.toFixed(2)}:1, needs ${need}:1`)
      }
    }
    for (const fill of ['primary', 'primary-hover']) {
      const ratio = contrast(values['on-primary'], values[fill])
      if (ratio < 4.5) found.push(`${name} on-primary on ${fill}: ${ratio.toFixed(2)}:1, needs 4.5:1`)
    }
  }
  return found
}

if (process.argv.includes('--check')) {
  const failures = problems()
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {}
  if (current !== render()) failures.unshift('site/theme/tokens.css is not what tools/site_tokens.mjs writes; run it')
  if (failures.length) {
    console.error(failures.join('\n'))
    process.exit(1)
  }
  console.log(`tokens ok (${ROLES.length} roles in 2 schemes)`)
} else {
  writeFileSync(OUT, render())
  const failures = problems()
  if (failures.length) console.error(failures.join('\n'))
  console.log(`wrote ${OUT}`)
}
