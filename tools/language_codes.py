"""Generate UI display metadata without changing stored or wire language identities."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# The recognition language table the core compiles in (native/core/src/languages.rs).
SOURCE = ROOT / "native/core/data/transcription_languages.json"
OUTPUT = ROOT / "src-ui/logics/common/languageCodes.ts"


def language_codes():
    table = json.loads(SOURCE.read_text(encoding="utf-8"))
    return {language: {country: codes.get("Google") for country, codes in countries.items()}
            for language, countries in table.items()}


def render():
    return ("// Generated by python tools/language_codes.py --write; do not edit.\n"
            "// Google tags from native/core/data/transcription_languages.json.\n"
            "// English language name -> English country name -> BCP-47 tag.\n"
            "export type LanguageCodes = Readonly<Record<string, Readonly<Record<string, string>>>>;\n\n"
            "export const languageCodes: LanguageCodes = "
            + json.dumps(language_codes(), ensure_ascii=False, indent=4) + ";\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Update the generated UI table")
    args = parser.parse_args()
    expected = render()
    if args.write:
        OUTPUT.write_text(expected, encoding="utf-8")
        return 0
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
        print("UI language tags are stale; run python tools/language_codes.py --write")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
