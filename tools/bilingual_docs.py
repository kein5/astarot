#!/usr/bin/env python3
"""Check that the bilingual documents carry both versions with the same section structure.

The English version of every document and every piece of agent reference material is the
authoritative one, and the Japanese version is made from it (AGENTS.md, "English and Japanese").
A bilingual file takes this form (the docs skill, section 3):

    # <title>
    [日本語版](#<the anchor of the Japanese title>)
    <the English version>

    ---

    # <title>（日本語版）
    <the Japanese version>

    python tools/bilingual_docs.py --check   # exit 1 on any problem below

--check reads the root *.md, docs/ and skills/ and reports, for each file:

- a file with no Japanese version (an H1 ending in "（日本語版）"), unless it is listed below
  as exempt, as a skill not yet converted, or as one of the paired README files;
- a Japanese version without the divider (a line "---" after a blank line) before its title,
  an English version that is missing or comes second, and a missing link from the English
  title to the Japanese title;
- headings that differ between the versions. Below the two titles, the headings must pair off
  one to one, in the same order: the same level, the same section number when the English
  heading starts with one (1., 3.1, D., P-01), the same inline code and the same emoji. The
  English headings contain no kana;
- for a converted skill, a description in its front matter that does not start in Japanese
  and stays within the 1,024 characters of the Agent Skills format.

What it cannot check: whether the two versions say the same thing. A machine cannot judge that
two sentences in different languages mean the same, so the check stops at the structure. The
rule (English first, the Japanese in the same pull request) and review cover the rest. The UI
text in locales/ has its own check (tools/i18n_gate).

Messages are ASCII apart from quoted headings, and stdout replaces what a Windows console
cannot print.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import unicodedata
from itertools import takewhile
from pathlib import Path, PurePosixPath
from typing import NamedTuple

ROOT = Path(__file__).resolve().parents[1]

JA_SUFFIX = "（日本語版）"
DIVIDER = "---"

# Files in scope that carry one language, or a Japanese version that is not a translation.
EXEMPT = {
    "NOTICE.md": "legal text, English only",
    "CODE_OF_CONDUCT.md": "adapted from the Contributor Covenant; the English text applies and the Japanese "
                          "is a summary of it",
    "docs/readmes/README.en.md": "a pointer to the English README at the repository root",
    "docs/spec/reference/config-keys.md": "generated by tools/spec_catalog.py, in Japanese only",
    "docs/spec/reference/error-codes.md": "generated by tools/spec_catalog.py, in Japanese only",
    "docs/spec/reference/ipc-endpoints.md": "generated by tools/spec_catalog.py, in Japanese only",
}

# The GitHub community files kept their headings and anchors when they took the common form
# (2026-11-24): the Japanese version sits under an H2 "<title>（日本語）", one level down.
SHIFTED = {"ACCESSIBILITY.md", "SECURITY.md", "SUPPORT.md"}
SHIFTED_SUFFIX = "（日本語）"

# GitHub shows README.md at the root, so its Japanese version is a file of its own.
PAIRS = {"README.md": "docs/readmes/README.ja.md"}

# Skills still written in Japanese only, until each one's pull request for #1367 converts it and
# removes its line. A blank line separates the lines, so that pull requests made side by side do
# not conflict when each removes its own.
PENDING_SKILLS = (
    "skills/adr/SKILL.md",

    "skills/ci-triage/SKILL.md",

    "skills/e2e/SKILL.md",

    "skills/jp-writing/SKILL.md",

    "skills/pull-request/SKILL.md",

    "skills/real-machine-check/SKILL.md",

    "skills/release/SKILL.md",

    "skills/release-notes/SKILL.md",

    "skills/testing/SKILL.md",
)

# Sections that exist only in the Japanese version. Each is left out of the comparison until its
# English version is written; the check fails once the heading is gone, so that the entry goes too.
JAPANESE_ONLY_SECTIONS = {
    "docs/spec/ipc-protocol.md": ("設定ファイルと会話ログの保存先",),
    "docs/voice-stack/licensing.md": ("おしゃべりAIの画面のJPEG変換（#388）",),
}

# The Agent Skills format's limit for a skill's description, which the English and the Japanese
# share once a skill carries both.
DESCRIPTION_LIMIT = 1024

SCOPE_DIRS = ("docs", "skills")
SKIPPED_DIRS = {".git", "node_modules", "target", "dist", "build", ".venv"}

FENCE = re.compile(r"^\s*(`{3,}|~{3,})")
HEADING = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*$")
LINK_TARGET = re.compile(r"\]\(([^)\s]+)\)")
SECTION_NUMBER = re.compile(r"^(\d+(?:\.\d+)*\.?|[A-Z]\.|[A-Z]+-\d+)(?=\s)")
CODE_SPAN = re.compile(r"`([^`]+)`")
KANA = re.compile(r"[\u3040-\u30ff]")  # hiragana and katakana


class Heading(NamedTuple):
    line: int  # 1-based
    level: int
    text: str


def anchor(text: str) -> str:
    """The id GitHub gives a heading: the rendered text in lower case, punctuation (full-width too)
    left out, a hyphen for each space. Kana and kanji stay (as tools/changelog.py does)."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text).replace("`", "")
    return re.sub(r"[^\w\- ]", "", text).lower().replace(" ", "-")


def front_matter_end(lines: list[str]) -> int:
    """The index of the first line after a YAML front matter block, or 0 without one."""
    if lines and lines[0].strip() == DIVIDER:
        for index in range(1, len(lines)):
            if lines[index].strip() == DIVIDER:
                return index + 1
    return 0


def headings(lines: list[str], start: int = 0) -> list[Heading]:
    """The ATX headings outside code fences and HTML comments, from line index `start` on."""
    found = []
    fence = ""
    comment = False
    for index in range(start, len(lines)):
        line = lines[index]
        if fence:
            stripped = line.strip()
            if stripped.startswith(fence) and not stripped.strip(fence[0]):
                fence = ""
            continue
        if comment:
            comment = "-->" not in line
            continue
        match = FENCE.match(line)
        if match:
            fence = match.group(1)
            continue
        if line.lstrip().startswith("<!--"):
            comment = "-->" not in line
            continue
        match = HEADING.match(line)
        if match:
            found.append(Heading(index + 1, len(match.group(1)), (match.group(2) or "").strip()))
    return found


def name_in_front_matter(lines: list[str], end: int) -> bool:
    return any(re.match(r"name:\s*\S", line) for line in lines[1:max(end - 1, 1)])


def symbols(text: str) -> list[str]:
    return sorted(char for char in text if unicodedata.category(char) == "So")


def compare(path: str, english: list[Heading], japanese: list[Heading], offset: int, errors: list[str]) -> None:
    """Pair the headings off in order and report the first place where the two versions part."""
    for heading in english:
        if KANA.search(heading.text):
            errors.append(f"{path}:{heading.line}: the English version has a heading in Japanese: "
                          f"{heading.text!r}")
    for index in range(max(len(english), len(japanese))):
        en = english[index] if index < len(english) else None
        ja = japanese[index] if index < len(japanese) else None
        if en is None:
            errors.append(f"{path}:{ja.line}: the Japanese heading {ja.text!r} has no English heading "
                          f"to match; write the English section first")
            return
        if ja is None:
            errors.append(f"{path}:{en.line}: the English heading {en.text!r} has no Japanese heading "
                          f"to match")
            return
        problem = None
        if en.level + offset != ja.level:
            problem = f"level {en.level} in English but {ja.level - offset} in Japanese"
        elif sorted(CODE_SPAN.findall(en.text)) != sorted(CODE_SPAN.findall(ja.text)):
            problem = "different inline code"
        elif symbols(en.text) != symbols(ja.text):
            problem = "different emoji"
        else:
            number = SECTION_NUMBER.match(en.text)
            if number:
                label = number.group(1)
                rest = ja.text[len(label):]
                if not ja.text.startswith(label) or (rest[:1].isdigit()):
                    problem = f"the Japanese heading does not start with the number {label!r} of the English one"
        if problem:
            errors.append(f"{path}:{en.line}: headings part at {en.text!r} (line {en.line}) and {ja.text!r} "
                          f"(line {ja.line}): {problem}")
            return


def check_skill_description(path: str, lines: list[str], end: int, errors: list[str]) -> None:
    """A converted skill's description leads in English and stays within the format's limit."""
    body = lines[1:max(end - 1, 1)]
    for index, line in enumerate(body):
        match = re.match(r"description:\s*(.*)$", line)
        if not match:
            continue
        text = match.group(1).strip()
        if text in (">", ">-", "|", "|-"):  # a block scalar: the indented lines that follow
            text = " ".join(next_line.strip() for next_line in
                            takewhile(lambda next_line: next_line.startswith((" ", "\t")), body[index + 1:]))
        text = text.strip("'\"")
        if len(text) > DESCRIPTION_LIMIT:
            errors.append(f"{path}:{index + 2}: the description has {len(text)} characters; the limit is "
                          f"{DESCRIPTION_LIMIT}")
        if not text[:1].isascii():
            errors.append(f"{path}:{index + 2}: the description starts in Japanese; put the English first")
        return
    errors.append(f"{path}:1: no description in the front matter")


def split_japanese(path: str, hs: list[Heading]) -> tuple[Heading | None, int]:
    """The Japanese title and how many levels the Japanese version sits below the English one."""
    if path in SHIFTED:
        titles = [h for h in hs if h.level == 2 and h.text.endswith(SHIFTED_SUFFIX)]
        return (titles[0] if titles else None), 1
    titles = [h for h in hs if h.level == 1 and h.text.endswith(JA_SUFFIX)]
    return (titles[0] if titles else None), 0


def check_file(root: Path, path: str, errors: list[str]) -> None:
    lines = (root / path).read_text(encoding="utf-8").splitlines()
    start = front_matter_end(lines)
    hs = headings(lines, start)
    title, offset = split_japanese(path, hs)
    pending = path in PENDING_SKILLS
    if title is None:
        if not pending:
            errors.append(f"{path}:1: no Japanese version (a heading '# <title>{JA_SUFFIX}' after the "
                          f"English version and a '---' line)")
        return
    if pending:
        errors.append(f"{path}:1: this skill is bilingual now; remove it from PENDING_SKILLS in "
                      f"tools/bilingual_docs.py")
    if path.startswith("skills/"):
        check_skill_description(path, lines, start, errors)
    if len([h for h in hs if h.level == title.level and h.text == title.text]) > 1:
        errors.append(f"{path}:{title.line}: more than one Japanese title {title.text!r}")

    before = [line.strip() for line in lines[start:title.line - 1]]
    while before and not before[-1]:
        before.pop()
    if not before or before[-1] != DIVIDER or len(before) < 2 or before[-2]:
        errors.append(f"{path}:{title.line}: put the divider before the Japanese title: '---' on a line "
                      f"of its own, after a blank line")
    if not any(line and line != DIVIDER for line in before):
        errors.append(f"{path}:{title.line}: no English version before the Japanese one")
        return

    english = [h for h in hs if h.line < title.line]
    japanese = [h for h in hs if h.line > title.line]
    if english and english[0].level == title.level - offset:
        english_title = english.pop(0)
        top = english_title.line
    elif name_in_front_matter(lines, start):
        top = start  # the front matter names the document (DESIGN.md)
    else:
        errors.append(f"{path}:{start + 1}: the English version starts without its title "
                      f"('# <title>' before the Japanese one)")
        return
    if not KANA.search("\n".join(lines[title.line:])):
        errors.append(f"{path}:{title.line}: the Japanese version contains no Japanese text")

    # The link to the Japanese version, between the English title and the English sections.
    link_end = english[0].line - 1 if english else title.line - 1
    target = "#" + anchor(title.text)
    if not any(target in LINK_TARGET.findall(line) for line in lines[top:link_end]):
        errors.append(f"{path}:{top + 1}: link to the Japanese version under the English title: "
                      f"[日本語版]({target})")

    skipped = JAPANESE_ONLY_SECTIONS.get(path, ())
    for text in skipped:
        if not any(h.text == text for h in japanese):
            errors.append(f"{path}:1: the Japanese-only section {text!r} is gone; remove it from "
                          f"JAPANESE_ONLY_SECTIONS in tools/bilingual_docs.py")
    japanese = [h for h in japanese if h.text not in skipped]
    compare(path, english, japanese, offset, errors)


def check_pair(root: Path, english_path: str, japanese_path: str, errors: list[str]) -> None:
    """A document kept as two files: both exist, link to each other and have the same headings."""
    if not (root / japanese_path).is_file():
        errors.append(f"{english_path}:1: its Japanese version {japanese_path} does not exist")
        return
    english_lines = (root / english_path).read_text(encoding="utf-8").splitlines()
    japanese_lines = (root / japanese_path).read_text(encoding="utf-8").splitlines()
    for path, lines, other in ((english_path, english_lines, japanese_path),
                               (japanese_path, japanese_lines, english_path)):
        targets = [target for line in lines for target in LINK_TARGET.findall(line)]
        if not any(target.split("#", 1)[0].lstrip("/").endswith(other) for target in targets):
            errors.append(f"{path}:1: no link to {other}")
    compare(f"{english_path} and {japanese_path}", headings(english_lines), headings(japanese_lines), 0, errors)


def markdown_files(root: Path) -> list[str]:
    """The root *.md and the Markdown under docs/ and skills/, as git sees them (untracked files
    included, ignored ones left out), or from the file system outside a git checkout."""
    try:
        run = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--cached", "--others",
                              "--exclude-standard", "--", "*.md"], capture_output=True, text=True,
                             check=True, encoding="utf-8")
        names = [name for name in run.stdout.split("\0") if name and (root / name).is_file()]
        if names:
            return sorted(name for name in names if in_scope(name))
    except (OSError, subprocess.CalledProcessError):
        pass
    found = [path.name for path in root.glob("*.md")]
    for directory in SCOPE_DIRS:
        for current, subdirs, files in os.walk(root / directory):
            subdirs[:] = [d for d in subdirs if d not in SKIPPED_DIRS]
            found += [Path(current, name).relative_to(root).as_posix() for name in files if name.endswith(".md")]
    return sorted(found)


def in_scope(name: str) -> bool:
    parts = PurePosixPath(name).parts
    return len(parts) == 1 or parts[0] in SCOPE_DIRS


def check(root: Path) -> list[str]:
    errors: list[str] = []
    files = markdown_files(root)
    present = set(files)
    listed = {**{path: "EXEMPT" for path in EXEMPT}, **{path: "SHIFTED" for path in SHIFTED},
              **{path: "PENDING_SKILLS" for path in PENDING_SKILLS},
              **{path: "JAPANESE_ONLY_SECTIONS" for path in JAPANESE_ONLY_SECTIONS},
              **{path: "PAIRS" for path in (*PAIRS, *PAIRS.values())}}
    for path, table in sorted(listed.items()):
        if path not in present:
            errors.append(f"{path}: listed in {table} in tools/bilingual_docs.py but not found")
    paired = set(PAIRS.values())
    for path in files:
        if path in EXEMPT or path in paired:
            continue
        if path in PAIRS:
            check_pair(root, path, PAIRS[path], errors)
        else:
            check_file(root, path, errors)
    return errors


def main(argv: list[str] | None = None, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", required=True,
                        help="exit 1 when a bilingual document lacks a version or its headings differ")
    parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="backslashreplace")
    errors = check(root)
    for error in errors:
        print(error)
    if errors:
        print(f"{len(errors)} problem(s). The form and the rule: AGENTS.md (\"English and Japanese\") "
              f"and the docs skill.")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
