@dataclass
class Component:
    id: str
    name: str
    kind: str = ""
    role: str = ""
    role_ja: str = ""
    path: str = ""
    repository: str = ""
    status: str = ""
    status_ja: str = ""

    def text(self, field: str, lang: str) -> str:
        return getattr(self, field if lang == "en" else f"{field}_ja")


@dataclass
class Relation:
    source: str
    target: str
    line: str
    label: str = ""
    label_ja: str = ""


@dataclass
class ComponentMap:
    system: Component
    components: list[Component]
    relations: list[Relation]


# --- reading and validating the data ----------------------------------------------------------

def text(table: dict, key: str, where: str, errors: list[str], *, required: bool = True) -> str:
    """A field holding one line of text; '' when it is absent or not valid."""
    value = table.get(key)
    if value is None:
        if required:
            errors.append(f"{where}: missing '{key}'")
        return ""
    if not isinstance(value, str) or not value.strip() or value != value.strip() or "\n" in value:
        errors.append(f"{where}: '{key}' must be one line of text without spaces at either end")
        return ""
    return value


def unknown_fields(table: dict, allowed: tuple[str, ...], where: str, errors: list[str]) -> None:
    errors += [f"{where}: unknown field '{key}'" for key in table if key not in allowed]


def paired(table: dict, key: str, where: str, errors: list[str]) -> tuple[str, str]:
    """An optional English text and its Japanese version, which are given together or not at all."""
    english = text(table, key, where, errors, required=False)
    japanese = text(table, f"{key}_ja", where, errors, required=False)
    if (key in table) != (f"{key}_ja" in table):
        errors.append(f"{where}: give '{key}' and '{key}_ja' together")
    return english, japanese


def table_list(data: dict, key: str, errors: list[str]) -> list[dict]:
    entries = data.get(key, [])
    if not isinstance(entries, list) or not all(isinstance(entry, dict) for entry in entries):
        errors.append(f"{DATA}: write each {key} as a [[{key}]] table")
        return []
    return entries


def read_system(data: dict, errors: list[str]) -> Component:
    table = data.get("system")
    where = f"{DATA}: [system]"
    if not isinstance(table, dict):
        errors.append(f"{where} is required")
        table = {}
    unknown_fields(table, SYSTEM_FIELDS, where, errors)
    system = Component(id=text(table, "id", where, errors), name=text(table, "name", where, errors),
                       repository=text(table, "repository", where, errors))
    if system.repository and not REPOSITORY.fullmatch(system.repository):
        errors.append(f"{where}: repository must be 'owner/name'")
    return system


def read_component(root: Path, table: dict, where: str, errors: list[str]) -> Component:
    unknown_fields(table, COMPONENT_FIELDS, where, errors)
    component = Component(id=text(table, "id", where, errors), name=text(table, "name", where, errors),
                          kind=text(table, "kind", where, errors), role=text(table, "role", where, errors),
                          role_ja=text(table, "role_ja", where, errors))
    component.status, component.status_ja = paired(table, "status", where, errors)
    if component.kind and component.kind not in KINDS:
        errors.append(f"{where}: kind must be one of {', '.join(KINDS)}")
    if component.kind == "internal":
        component.path = text(table, "path", where, errors)
        if "repository" in table:
            errors.append(f"{where}: an internal component has a path, not a repository")
        if component.path and (not FOLDER.fullmatch(component.path) or ".." in component.path.split("/")):
            errors.append(f"{where}: path must be a plain folder path in the repository")
        elif component.path and not (root / component.path).is_dir():
            errors.append(f"{where}: path {component.path} is not a folder in the repository")
    elif component.kind == "external":
        component.repository = text(table, "repository", where, errors)
        if "path" in table:
            errors.append(f"{where}: an external component has a repository, not a path")
        if component.repository and not REPOSITORY.fullmatch(component.repository):
            errors.append(f"{where}: repository must be 'owner/name'")
    return component


def read_relation(table: dict, where: str, ids: set[str], errors: list[str]) -> Relation:
    unknown_fields(table, RELATION_FIELDS, where, errors)
    relation = Relation(source=text(table, "from", where, errors), target=text(table, "to", where, errors),
                        line=text(table, "line", where, errors))
    relation.label, relation.label_ja = paired(table, "label", where, errors)
    for key, value in (("from", relation.source), ("to", relation.target)):
        if value and value not in ids:
            errors.append(f"{where}: '{key}' names {value}, which is not the system or a component")
    if relation.source and relation.source == relation.target:
        errors.append(f"{where}: a relation joins two different entries")
    if relation.line and relation.line not in LINES:
        errors.append(f"{where}: line must be one of {', '.join(LINES)}")
    return relation


def load(root: Path, errors: list[str]) -> ComponentMap | None:
    """The map in the data file, or None when the file cannot be read as TOML."""
    try:
        data = tomllib.loads((root / DATA).read_text(encoding="utf-8"))
    except FileNotFoundError:
        errors.append(f"{DATA} does not exist")
        return None
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        errors.append(f"{DATA}: cannot be read as TOML ({exc})")
        return None
    errors += [f"{DATA}: unknown table '{key}'" for key in data if key not in ("system", "component", "relation")]
    system = read_system(data, errors)
    components = [read_component(root, table, f"{DATA}: component {number}", errors)
                  for number, table in enumerate(table_list(data, "component", errors), 1)]
    if not any(component.kind == "internal" for component in components):
        errors.append(f"{DATA}: no internal component is listed")

    seen_ids: set[str] = set()
    seen_names: set[str] = set()
    for entry in (system, *components):
        if entry.id:
            if not ID.fullmatch(entry.id) or entry.id in RESERVED_IDS:
                errors.append(f"{DATA}: id '{entry.id}' must be lower case letters, digits and '_', and not a "
                              "Mermaid keyword")
            elif entry.id in seen_ids:
                errors.append(f"{DATA}: id '{entry.id}' is used twice")
            seen_ids.add(entry.id)
        if entry.name:
            if entry.name in seen_names:
                errors.append(f"{DATA}: name '{entry.name}' is used twice")
            seen_names.add(entry.name)
    paths = [component.path for component in components if component.path]
    errors += [f"{DATA}: path {path} is given twice" for path in sorted({p for p in paths if paths.count(p) > 1})]

    relations = [read_relation(table, f"{DATA}: relation {number}", seen_ids, errors)
                 for number, table in enumerate(table_list(data, "relation", errors), 1)]
    return ComponentMap(system, components, relations)


# --- comparing with the Cargo packages ------------------------------------------------------------

def cargo_packages(root: Path, warnings: list[str]) -> dict[str, str]:
    """Folder (relative to the root) -> package name of each Cargo package found as the docstring says."""
    base = root.resolve()
    queue = [base / "Cargo.toml", base / "src-tauri" / "Cargo.toml", *sorted((base / "native").glob("*/Cargo.toml"))]
    packages: dict[str, str] = {}
    seen: set[Path] = set()
    while queue:
        manifest = queue.pop(0).resolve()
        if manifest in seen or not manifest.is_file():
            continue
        seen.add(manifest)
        try:
            folder = manifest.parent.relative_to(base).as_posix()
        except ValueError:
            continue
        try:
            data = tomllib.loads(manifest.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError):
            warnings.append(f"warning: {folder}/Cargo.toml cannot be read as TOML; it was not compared with the map")
            continue
        package = data.get("package")
        if isinstance(package, dict):
            packages[folder] = str(package.get("name", folder))
        workspace = data.get("workspace")
        members = workspace.get("members", []) if isinstance(workspace, dict) else []
        for pattern in members if isinstance(members, list) else []:
            if isinstance(pattern, str):
                queue += sorted(member / "Cargo.toml" for member in manifest.parent.glob(pattern) if member.is_dir())
    return packages


def unmapped(root: Path, components: list[Component]) -> list[str]:
    """A warning for each Cargo package whose folder no entry gives as its path."""
    warnings: list[str] = []
    named = {component.path for component in components if component.path}
    for folder, name in sorted(cargo_packages(root, warnings).items()):
        if folder not in named:
            warnings.append(f"warning: the Cargo package {name} ({folder}) has no entry in {DATA}")
    return warnings


# --- rendering --------------------------------------------------------------------------------------

def mermaid_text(value: str) -> str:
    """Text for a quoted Mermaid label, with the characters that would end or mark up the label escaped."""
    return value.replace("&", "#amp;").replace('"', "#quot;").replace("<", "#lt;").replace(">", "#gt;")


def label(name: str, *lines: str) -> str:
    return "<b>" + mermaid_text(name) + "</b>" + "".join("<br/>" + mermaid_text(line) for line in lines)


def role_with_status(component: Component, lang: str) -> str:
    role, status = component.text("role", lang), component.text("status", lang)
    if not status:
        return role
    return f"{role} ({status})" if lang == "en" else f"{role}（{status}）"


def diagram(model: ComponentMap, lang: str) -> list[str]:
    """The Mermaid flowchart. Its labels are the English texts in both versions of the page."""
    words = WORDS[lang]
    internal = [component for component in model.components if component.kind == "internal"]
    external = [component for component in model.components if component.kind == "external"]
    system = model.system
    # The diagram is checked to render with Mermaid 11 and 12. Mermaid 12 lays a flowchart out with
    # ELK, which draws a hop where two lines cross and then redraws the dashed line of a hop as a
    # solid one; the front matter turns the hops off. Mermaid 11 ignores the setting.
    # The title of the system's box stays on one line: Mermaid 11 hides a second line behind the nodes.
    lines = ["```mermaid", "---", "config:", "  elk:", "    lineHops: false", "---", "flowchart TB",
             f"  accTitle: {words.get('diagram_title', words['title'])}",
             f"  accDescr: {words['description']}",
             f'  subgraph {system.id}["{label(system.name)} ({mermaid_text(system.repository)})"]']
    lines += [f'    {component.id}["{label(component.name, role_with_status(component, "en"))}"]'
              for component in internal]
    lines.append("  end")
    lines += [f'  {component.id}["{label(component.name, component.repository, role_with_status(component, "en"))}"]'
              for component in external]
    # Invisible links stack the internal components in rows of ROW, in the order of the data.
    lines += [f"  {upper.id} ~~~ {lower.id}" for upper, lower in zip(internal, internal[ROW:])]
    # Mermaid 11 ranks a node linked to the system's box right below the box's first node, beside
    # the box. An invisible link from the last internal component puts every external repository
    # that no internal component links to below the box instead.
    internal_ids = {component.id for component in internal}
    linked = {relation.target for relation in model.relations if relation.source in internal_ids}
    linked |= {relation.source for relation in model.relations if relation.target in internal_ids}
    lines += [f"  {internal[-1].id} ~~~ {component.id}" for component in external if component.id not in linked]
    for relation in model.relations:
        on_line = f'|"{mermaid_text(relation.label)}"|' if relation.label else ""
        lines.append(f"  {relation.source} {LINES[relation.line]}{on_line} {relation.target}")
    lines.append("```")
    return lines


def cell(value: str) -> str:
    """Text for a Markdown table cell: on one line, with '|' escaped and no HTML tags."""
    return re.sub(r"\s+", " ", value).replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;").strip()


def table(head: tuple[str, ...], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|",
            *("| " + " | ".join(row) + " |" for row in rows)]


def with_status(head: tuple[str, ...], rows: list[list[str]], components: list[Component], lang: str):
    """The table's columns and rows, with a status column only when an entry has a status."""
    if not any(component.status for component in components):
        return head, rows
    return (*head, WORDS[lang]["status"]), [row + [cell(component.text("status", lang))]
                                            for row, component in zip(rows, components)]


def version(model: ComponentMap, lang: str) -> list[str]:
    """One language's version of the page."""
    words = WORDS[lang]
    internal = [component for component in model.components if component.kind == "internal"]
    external = [component for component in model.components if component.kind == "external"]
    names = {model.system.id: model.system.name, **{component.id: component.name for component in model.components}}

    lines = [f"# {words['title']}", ""]
    if "link" in words:
        lines += [words["link"], ""]
    lines += [words["intro"], "", f"## {words['diagram']}", "", words["text_version"], "", *diagram(model, lang), ""]

    head, rows = with_status(words["inside_columns"],
                             [[cell(c.name), cell(c.text("role", lang)), f"`{c.path}`"] for c in internal],
                             internal, lang)
    lines += [f"## {words['inside']}", "", *table(head, rows), ""]

    head, rows = with_status(words["external_columns"],
                             [[cell(c.name), f"[{c.repository}](https://github.com/{c.repository})",
                               cell(c.text("role", lang))] for c in external],
                             external, lang)
    lines += [f"## {words['external']}", "", *table(head, rows), ""]

    rows = [[cell(names[r.source]), cell(names[r.target]), words["lines"][r.line],
             cell(r.label if lang == "en" else r.label_ja)] for r in model.relations]
    lines += [f"## {words['relations']}", "", *table(words["relation_columns"], rows), ""]
    lines += [f"## {words['updating']}", "", words["updating_text"], ""]
    return lines


def render(model: ComponentMap) -> str:
    return "\n".join([NOTE, "", *version(model, "en"), "---", "", *version(model, "ja")]).rstrip("\n") + "\n"


# --- command line -----------------------------------------------------------------------------------

def main(argv: list[str] | None = None, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help=f"regenerate {PAGE} from {DATA}")
    mode.add_argument("--check", action="store_true",
                      help=f"exit 1 when {DATA} has a problem or {PAGE} is out of date")
    args = parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="backslashreplace")

    errors: list[str] = []
    model = load(root, errors)
    if model is not None and not errors:
        expected = render(model)
        page = root / PAGE
        current = page.read_text(encoding="utf-8") if page.is_file() else None
        if args.write and current != expected:
            page.parent.mkdir(parents=True, exist_ok=True)
            with open(page, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(expected)
            print(f"wrote {PAGE}")
        elif args.check and current != expected:
            errors.append(f"{PAGE} is out of date with {DATA}; run python tools/component_map.py --write")
    if model is not None:
        for warning in unmapped(root, model.components):
            print(warning)
    for error in errors:
        print(error)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
