#!/usr/bin/env python3
"""Generate the component map of the ASTAROT ecosystem from its data file.

tools/component_map.toml lists the components inside ASTAROT and the repositories kept
outside it, by code name (the naming record is Issue #689). It is the only place where the
map's names and roles are edited. This tool makes docs/component-map.md from it: a Mermaid
diagram and tables, the English version first and the Japanese version after it.

    python tools/component_map.py --write   # regenerate the page
    python tools/component_map.py --check   # exit 1 when the data has a problem or the page is out of date

Both modes also compare the data with the Cargo packages of the repository and print a
warning, without changing the exit code, for each package whose folder no entry names as its
path. A new crate then shows up instead of silently missing from the map. The repository
has no top-level Cargo workspace: the app (src-tauri) and each crate in native/ is a
workspace of its own (CARGO_WORKSPACES in tools/dev.py). So the comparison reads Cargo.toml
at the root, in src-tauri and in each folder of native/, plus the members that any of them
lists under [workspace]. Code that is not a Cargo package, such as the UI or the C helper
programs in native/, is not found this way.

Only the standard library is used (tomllib needs Python 3.11). Messages are ASCII apart from
quoted values, and stdout replaces what a Windows console cannot print.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
DATA = PurePosixPath("tools/component_map.toml")
PAGE = PurePosixPath("docs/component-map.md")
NOTE = ("<!-- Generated by tools/component_map.py from tools/component_map.toml. "
        "Do not edit by hand; run `python tools/component_map.py --write`. -->")

KINDS = ("internal", "external")
# Mermaid's link for each kind of line.
LINES = {"solid": "---", "dashed": "-.-"}
# Internal components per row of the diagram.
ROW = 3

SYSTEM_FIELDS = ("id", "name", "repository")
COMPONENT_FIELDS = ("id", "name", "kind", "role", "role_ja", "path", "repository", "status", "status_ja")
RELATION_FIELDS = ("from", "to", "line", "label", "label_ja")

ID = re.compile(r"[a-z][a-z0-9_]*")
# Words that Mermaid's flowchart grammar reads as keywords, so they cannot be node ids.
RESERVED_IDS = {"end", "graph", "flowchart", "subgraph", "direction", "style", "class", "classdef", "click",
                "linkstyle", "default"}
REPOSITORY = re.compile(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+")
FOLDER = re.compile(r"[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)*")

